# Loop 1 — print each fruit
print("Loop 1:")
fruits = ["apple", "banana", "cherry", "mango"]
for fruit in fruits:
    print(fruit)

# Loop 2 — print each letter of your name
print("Loop 2:")
name = "Dhanushka"
for letter in name:
    print(letter)

# Loop 3 — calculate total of prices
print("Loop 3:")
prices = [150, 250, 75, 500, 100]
total = 0
for price in prices:
    total = total + price
print(f"Total: ${total}")