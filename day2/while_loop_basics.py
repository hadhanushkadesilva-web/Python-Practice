# Loop 1 — countdown
print("Loop 1: Countdown")
n = 5
while n > 0:
    print(n)
    n = n - 1
print("Liftoff! 🚀")

# Loop 2 — sum the numbers 1 to 10
print("Loop 2: Sum 1 to 10")
i = 1
total = 0
while i <= 10:
    total = total + i
    i = i + 1
print(f"Total: {total}")

